export type IconName = keyof typeof ICONS;

export function icon(name: string, cls = ''): SVGSVGElement {
  const grid = ICONS[name] ?? ICONS.x;
  const rects: SVGElement[] = [];
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.') {
        x++;
        continue;
      }
      let end = x;
      while (end < row.length && row[end] === ch) end++;
      rects.push(s('rect', { x, y, width: end - x, height: 1, fill: 'currentColor', 'fill-opacity': ch === 'o' ? 0.35 : 1 }));
      x = end;
    }
  });
  return s('svg', { class: `px ${cls}`.trim(), viewBox: '0 0 12 12', 'aria-hidden': 'true' }, rects);
}

export function iconNames(): string[] {
  return Object.keys(ICONS);
}
